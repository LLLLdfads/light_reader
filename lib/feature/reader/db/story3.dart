import 'package:light_reader/feature/reader/model/book.dart';

Chapter _ch(int i, String title, String text) {
  assert(text.length <= 100, '${text.length} $title');
  return Chapter(
    id: '$i',
    chapterTitle: title,
    paragraphs: [text],
    bookName: '绿野仙踪',
  );
}

